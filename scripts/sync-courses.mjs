/* Builds src/data/courseCatalog.ts from the seed data: the courses (domains
 * that are for sale on their own) from backend/prisma/seed-data/courses.json,
 * and each course's modules and lessons from the domains/<track>/<domain>/ files.
 * Run it after any change to courses.json, a domains.json, modules.json or
 * lessons.json, and commit the result. src/data/__tests__/courseCatalog.test.ts
 * fails if the committed file has drifted.
 *
 *   node scripts/sync-courses.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SEED = join(ROOT, 'backend', 'prisma', 'seed-data');
const OUT = join(ROOT, 'src', 'data', 'courseCatalog.ts');

const readJson = (...p) => JSON.parse(readFileSync(join(SEED, ...p), 'utf-8'));

/** The course list, built from the seed data. Only domains with courseForSale true. */
export function buildCourseCatalog() {
  const courses = readJson('courses.json');
  const trackDirs = readdirSync(join(SEED, 'domains'), { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(SEED, 'domains', d.name, 'domains.json')))
    .map((d) => d.name)
    .sort();

  const out = [];
  for (const trackId of trackDirs) {
    for (const domain of readJson('domains', trackId, 'domains.json')) {
      const c = courses[domain.id];
      if (!c || !c.courseForSale) continue;
      const modules = readJson('domains', trackId, domain.slug, 'modules.json').sort((a, b) => a.order - b.order);
      const lessons = readJson('domains', trackId, domain.slug, 'lessons.json');
      const firstModule = modules[0];
      const firstLesson = lessons
        .filter((l) => l.moduleId === firstModule.id)
        .sort((a, b) => a.order - b.order)[0];
      out.push({
        slug: c.courseSlug,
        title: c.courseTitle,
        blurb: c.courseBlurb,
        order: c.courseOrder,
        trackId,
        domainKey: domain.id,
        firstLessonId: firstLesson.id,
        lessonCount: lessons.length,
        totalMinutes: lessons.reduce((n, l) => n + (l.duration ?? 0), 0),
        modules: modules.map((m) => ({
          // Display only: the seed keeps its punctuation, the catalog has no em dashes.
          title: m.title.replaceAll(' — ', ': '),
          lessonCount: lessons.filter((l) => l.moduleId === m.id).length,
        })),
      });
    }
  }
  return out.sort((a, b) => (a.trackId === b.trackId ? a.order - b.order : a.trackId < b.trackId ? -1 : 1));
}

function render(catalog) {
  return `// GENERATED by scripts/sync-courses.mjs from backend/prisma/seed-data. Do not edit by hand.
// Run \`node scripts/sync-courses.mjs\` after changing courses.json or any domain's
// modules.json or lessons.json. src/data/__tests__/courseCatalog.test.ts fails on drift.
//
// A course is a domain that is for sale on its own. Fully static on purpose,
// so the course pages work logged out and prerender.

export interface CourseModule {
  title: string;
  lessonCount: number;
}

export interface CatalogCourse {
  /** Public URL slug: /courses/<slug>. */
  slug: string;
  title: string;
  blurb: string;
  /** Position inside its track, 1 to 6. */
  order: number;
  trackId: string;
  /** The domain's id in the seed data. Checkout accepts it as a course id. */
  domainKey: string;
  /** Lesson 1 of module 1: the free one. */
  firstLessonId: string;
  lessonCount: number;
  totalMinutes: number;
  modules: CourseModule[];
}

export const COURSE_CATALOG: CatalogCourse[] = ${JSON.stringify(catalog, null, 2)};

export function getCourse(slug: string | undefined): CatalogCourse | undefined {
  return COURSE_CATALOG.find((c) => c.slug === slug);
}

export function coursesOfTrack(trackId: string): CatalogCourse[] {
  return COURSE_CATALOG.filter((c) => c.trackId === trackId).sort((a, b) => a.order - b.order);
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = buildCourseCatalog();
  writeFileSync(OUT, render(catalog), 'utf-8');
  console.log(`Wrote ${catalog.length} courses to src/data/courseCatalog.ts`);
  for (const c of catalog) console.log(`  ${c.trackId} #${c.order} ${c.slug}: ${c.modules.length} modules, ${c.lessonCount} lessons`);
}
